    public partial class CustomerRegistrationForm : Form
    {
        private readonly string connectionString =
            @"Data Source=.\SQLEXPRESS;Initial Catalog=eShiftTransportDB;Integrated Security=True;TrustServerCertificate=True;";

        public CustomerRegistrationForm()
        {
            InitializeComponent();

            // Connect the existing buttons.
            btnRegister.Click -= btnRegister_Click;
            btnRegister.Click += btnRegister_Click;

            btnClear.Click -= btnClear_Click;
            btnClear.Click += btnClear_Click;

            Button backButton = FindButton("btnBackToLogin");

            if (backButton != null)
            {
                backButton.Click -= btnBackToLogin_Click;
                backButton.Click += btnBackToLogin_Click;
            }

            // Password protection.
            txtPassword.UseSystemPasswordChar = true;

            TextBox confirmPassword =
                FindTextBox("txtConfirmPassword");

            if (confirmPassword != null)
                confirmPassword.UseSystemPasswordChar = true;

            // CustomerNumber is generated by the database.
            TextBox customerNumber =
                FindTextBox("txtCustomerNumber");

            if (customerNumber != null)
                customerNumber.ReadOnly = true;
        }

        // Keep this method for the existing Designer event.
        private void CustomerRegistrationForm_Load(
            object sender, EventArgs e)
        {
        }

        // Keep this method for the existing Designer event.
        private void pnlHeader_Paint(
            object sender, PaintEventArgs e)
        {
        }

        private TextBox FindTextBox(string name)
        {
            Control[] controls = Controls.Find(name, true);

            return controls.Length > 0
                ? controls[0] as TextBox
                : null;
        }

        private Button FindButton(string name)
        {
            Control[] controls = Controls.Find(name, true);

            return controls.Length > 0
                ? controls[0] as Button
                : null;
        }

        // Compatible with the PBKDF2 password format
        // used in the login code provided earlier.
        private string HashPassword(string password)
        {
            byte[] salt = new byte[16];

            using (var rng = RandomNumberGenerator.Create())
            {
                rng.GetBytes(salt);
            }

            const int iterations = 100000;
            byte[] hash;

            using (var pbkdf2 = new Rfc2898DeriveBytes(
                password, salt, iterations))
            {
                hash = pbkdf2.GetBytes(32);
            }

            return "PBKDF2$" + iterations + "$" +
                Convert.ToBase64String(salt) + "$" +
                Convert.ToBase64String(hash);
        }

        private void btnRegister_Click(object sender, EventArgs e)
        {
            TextBox customerNumber =
                FindTextBox("txtCustomerNumber");

            TextBox fullName =
                FindTextBox("txtFullName");

            TextBox address =
                FindTextBox("txtAddress");

            TextBox telephone =
                FindTextBox("txtTelephone");

            TextBox email =
                FindTextBox("txtEmail");

            TextBox confirmPassword =
                FindTextBox("txtConfirmPassword");

            if (customerNumber == null ||
                fullName == null ||
                address == null ||
                telephone == null ||
                email == null ||
                confirmPassword == null)
            {
                MessageBox.Show(
                    "Please check the registration textbox names.",
                    "Missing Controls",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);

                return;
            }

            string name = fullName.Text.Trim();
            string customerAddress = address.Text.Trim();
            string phone = telephone.Text.Trim();
            string customerEmail = email.Text.Trim();
            string username = txtUsername.Text.Trim();
            string password = txtPassword.Text;

            // Validate required fields.
            if (string.IsNullOrWhiteSpace(name) ||
                string.IsNullOrWhiteSpace(customerAddress) ||
                string.IsNullOrWhiteSpace(phone) ||
                string.IsNullOrWhiteSpace(customerEmail) ||
                string.IsNullOrWhiteSpace(username) ||
                string.IsNullOrWhiteSpace(password) ||
                string.IsNullOrWhiteSpace(confirmPassword.Text))
            {
                MessageBox.Show(
                    "Please fill in all required fields.",
                    "Missing Information",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Warning);

                return;
            }

            if (password.Length < 8)
            {
                MessageBox.Show(
                    "Your password must contain at least 8 characters.",
                    "Invalid Password",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Warning);

                return;
            }

            if (password != confirmPassword.Text)
            {
                MessageBox.Show(
                    "Password and Confirm Password do not match.",
                    "Password Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Warning);

                confirmPassword.Focus();
                return;
            }

            try
            {
                using (SqlConnection con =
                    new SqlConnection(connectionString))
                {
                    con.Open();

                    // Check whether the username already exists.
                    // CustomerNumber is deliberately not used here.
                    using (SqlCommand check = new SqlCommand(@"
SELECT COUNT(*)
FROM dbo.Customers
WHERE Username = @Username;", con))
                    {
                        check.Parameters.Add(
                            "@Username", SqlDbType.NVarChar, 100)
                            .Value = username;

                        int count =
                            Convert.ToInt32(check.ExecuteScalar());

                        if (count > 0)
                        {
                            MessageBox.Show(
                                "This username already exists. Please choose another.",
                                "Duplicate Username",
                                MessageBoxButtons.OK,
                                MessageBoxIcon.Warning);

                            return;
                        }
                    }

                    // CustomerNumber is generated by SQL Server.
                    // Do not include it in the INSERT statement.
                    using (SqlCommand cmd = new SqlCommand(@"
INSERT INTO dbo.Customers
(
    FullName,
    Address,
    Telephone,
    Email,
    Username,
    PasswordHash,
    CreatedAt,
    IsActive
)
OUTPUT INSERTED.CustomerNumber
VALUES
(
    @FullName,
    @Address,
    @Telephone,
    @Email,
    @Username,
    @PasswordHash,
    SYSDATETIME(),
    1
);", con))
                    {
                        cmd.Parameters.AddWithValue(
                            "@FullName", name);

                        cmd.Parameters.AddWithValue(
                            "@Address", customerAddress);

                        cmd.Parameters.AddWithValue(
                            "@Telephone", phone);

                        cmd.Parameters.AddWithValue(
                            "@Email", customerEmail);

                        cmd.Parameters.AddWithValue(
                            "@Username", username);

                        cmd.Parameters.AddWithValue(
                            "@PasswordHash", HashPassword(password));

                        object generatedNumber =
                            cmd.ExecuteScalar();

                        // Display the database-generated customer number.
                        if (generatedNumber != null &&
                            generatedNumber != DBNull.Value)
                        {
                            customerNumber.Text =
                                generatedNumber.ToString();
                        }
                    }
                }

                MessageBox.Show(
                    "Customer registered successfully!\n" +
                    "Your Customer Number is: " +
                    customerNumber.Text,
                    "Registration Successful",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Information);

                // Return to the login form.
                ShowLoginForm();
                Close();
            }
            catch (SqlException ex)
            {
                MessageBox.Show(
                    "Database registration failed:\n" + ex.Message,
                    "Database Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
            catch (Exception ex)
            {
                MessageBox.Show(
                    "Registration failed:\n" + ex.Message,
                    "Registration Error",
                    MessageBoxButtons.OK,
                    MessageBoxIcon.Error);
            }
        }

        private void btnClear_Click(object sender, EventArgs e)
        {
            ClearRegistrationFields();

            MessageBox.Show(
                "Registration fields cleared.",
                "Cleared",
                MessageBoxButtons.OK,
                MessageBoxIcon.Information);
        }

        private void ClearRegistrationFields()
        {
            string[] names =
            {
                "txtCustomerNumber",
                "txtFullName",
                "txtAddress",
                "txtTelephone",
                "txtEmail",
                "txtUsername",
                "txtPassword",
                "txtConfirmPassword"
            };

            foreach (string name in names)
            {
                TextBox textbox = FindTextBox(name);

                if (textbox != null)
                    textbox.Clear();
            }

            txtUsername.Focus();
        }

        private void btnBackToLogin_Click(
            object sender, EventArgs e)
        {
            ShowLoginForm();
            Close();
        }

        private void ShowLoginForm()
        {
            LoginForm login = null;

            foreach (Form form in Application.OpenForms)
            {
                if (form is LoginForm)
                {
                    login = (LoginForm)form;
                    break;
                }
            }

            if (login == null)
                login = new LoginForm();

            login.Show();
            login.BringToFront();
        }
    }
